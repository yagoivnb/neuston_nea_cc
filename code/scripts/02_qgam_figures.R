# ------------------------------------------------------------------------------
# 7. REVISED BIOLOGICAL HOVMÖLLER DIAGRAM (TENSOR PRODUCT)
# ------------------------------------------------------------------------------
message("Generating inverted Hovmöller matrices via Tensor Product smooths...")

df_all_filtered <- df_all |> filter(year >= 2014 & year <= 2025)

generar_hov_grid_inverted <- function(datos_especie) {
  mod <- qgam(decimalLatitude ~ te(yday, decimalYear, bs = c("cc", "tp")), data = datos_especie, qu = 0.5)
  grid <- expand.grid(yday = seq(1, 365, length.out = 100), decimalYear = seq(2014, 2025, length.out = 100))
  grid$pred_lat <- predict(mod, newdata = grid)
  grid$species <- unique(datos_especie$species)
  return(grid)
}

grid_hov_all <- bind_rows(
  generar_hov_grid_inverted(df_all_filtered |> filter(species == "Physalia")),
  generar_hov_grid_inverted(df_all_filtered |> filter(species == "Velella")),
  generar_hov_grid_inverted(df_all_filtered |> filter(species == "Neutral Neuston"))
)

hovmoller_bio_plot_inverted <- ggplot(grid_hov_all, aes(x = decimalYear, y = yday, fill = pred_lat)) +
  geom_tile() + 
  facet_wrap(~ species, ncol = 1, axes = "all_x") + 
  scale_fill_viridis_c(option = "turbo", name = "Latitude (°N)") +
  scale_x_continuous(breaks = seq(2014, 2025, by = 1), expand = c(0, 0), name = "Year") +
  scale_y_continuous(breaks = seq(15, 345, length.out = 12), labels = month.abb, expand = c(0, 0), name = "Month") +
  theme_minimal(base_size = 16) +
  theme(
    strip.text = element_text(face = "bold", size = 16),
    strip.background = element_rect(fill = "white", colour = NA),
    axis.text.x = element_text(angle = 45, hjust = 1, colour = "black"),
    axis.text.y = element_text(colour = "black"),
    panel.grid = element_blank(),
    axis.ticks = element_line(linewidth = 0.5),
    axis.line = element_line(linewidth = 0.5)
  )

ggsave("figures/exploratory/fig_S4_hovmoller_inverted.png", plot = hovmoller_bio_plot_inverted, 
       width = 10, height = 12, dpi = 300, bg = "white")

