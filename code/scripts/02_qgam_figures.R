# ------------------------------------------------------------------------------
# 3. CONSTRUCT BASE PLOTS (OVERLAID SPECIES)
# ------------------------------------------------------------------------------
# --- Seasonal (yday) ---
seasonal_plot_base <- ggplot() +
  geom_point(data = df_all, aes(x = yday, y = decimalLatitude, color = species, shape = species, fill = species), alpha = 0.2, size = 2) +
  geom_ribbon(data = effects_yday_all, aes(x = yday, ymin = latitud_lower, ymax = latitud_upper, fill = species), alpha = 0.2, color = NA) +
  geom_line(data = effects_yday_all, aes(x = yday, y = latitud_real, color = species), linewidth = 1.5) +
  scale_color_manual(values = col_map) +
