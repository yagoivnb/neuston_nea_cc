# ------------------------------------------------------------------------------
# 1. LOAD PRE-COMPUTED MODEL DATA
# ------------------------------------------------------------------------------
# Ingest the static mathematical outputs generated by 01_qgam_modelling.R
df_all           <- readRDS("data/processed/modelling_df_all.rds")
effects_yday_all <- readRDS("data/processed/modelling_effects_yday.rds")
effects_year_all <- readRDS("data/processed/modelling_effects_year.rds")

# ------------------------------------------------------------------------------
# 2. GLOBAL AESTHETIC CONFIGURATIONS
# ------------------------------------------------------------------------------
col_map <- c(
  "Physalia"         = "#7570b3",
  "Velella"          = "#1b9e77",
  "Neutral Neuston"  = "#d95f02"
)

shape_map <- c(
  "Physalia"         = 15,
  "Velella"          = 16,
  "Neutral Neuston"  = 17
)

# Standardised temporal breaks
month_breaks <- yday(as.Date(paste0("2020-", 1:12, "-01")))
month_labels <- month.abb

# Define visual limits for historical plotting to prevent unwarranted extrapolation
x_start <- 2014
x_end   <- max(df_all$decimalYear, na.rm = TRUE)

# Minimal theme template for base plots (No facets)
theme_base_plot <- theme_minimal(base_size = 20) +
  theme(
    panel.grid.major.x = element_line(colour = "grey85", linewidth = 0.5),
    panel.grid.minor.x = element_blank(),
    panel.grid.major.y = element_line(colour = "grey85", linewidth = 0.5),
    panel.grid.minor.y = element_line(colour = "grey90", linewidth = 0.5, linetype = "dashed"),
    axis.line.x = element_line(color = "black", linewidth = 0.8),
    axis.line.y = element_line(color = "black", linewidth = 0.8),
    axis.ticks = element_line(color = "black", linewidth = 0.6),
    axis.ticks.length = unit(0.18, "cm"),
    panel.border = element_blank(),
    legend.position = c(0.15, 0.9),
    legend.background = element_rect(fill = scales::alpha("white", 0.5), color = "black", linewidth = 0.3),
    legend.title = element_blank(),
    axis.title = element_text(face = "bold"),
    axis.text  = element_text(color = "black")
