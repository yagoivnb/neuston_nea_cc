# --- Historical (decimalYear) ---
historical_plot_base <- ggplot() +
  geom_ribbon(data = effects_year_all, aes(x = decimalYear, ymin = latitud_lower, ymax = latitud_upper, fill = species), alpha = 0.2, color = NA) +
  geom_line(data = effects_year_all, aes(x = decimalYear, y = latitud_real, color = species), linewidth = 1.5) +
  geom_point(data = df_all, aes(x = decimalYear, y = decimalLatitude, color = species, shape = species, fill = species), alpha = 0.15, size = 2) +
  scale_color_manual(values = col_map) +
  scale_fill_manual(values = col_map) +
  scale_shape_manual(values = shape_map) +
  scale_x_continuous(name = "", breaks = seq(floor(x_start), ceiling(x_end), by = 1), expand = c(0, 0)) +
  scale_y_continuous(name = "Latitude (°N)") +
  coord_cartesian(xlim = c(x_start, x_end)) +
  guides(fill = "none", color = guide_legend(override.aes = list(alpha = 1, linewidth = 1, size = 4))) +
  theme_base_plot

